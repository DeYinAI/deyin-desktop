/** Turns the parity tables into the Markdown that sits between the markers in `docs/PARITY-GROK-BOT.md`. */
import { ENUMS, SHAPES, SURFACES, type EnumParity, type ShapeParity, type SurfaceStatus } from "./table.js";
import { recoveredEnumValues, recoveredFieldNames } from "./recovered.js";

export const BEGIN_MARKER = "<!-- parity:begin (generated by test/parity/write.ts; do not edit by hand) -->";
export const END_MARKER = "<!-- parity:end -->";

export const STATUS_LABEL: Record<SurfaceStatus, string> = {
  done: "Done",
  foundation: "Foundation",
  "not-built": "Not built",
  different: "Deliberately different",
};

/** The Deyin value a recovered enum value corresponds to. */
export function ourValue(entry: EnumParity, recoveredValue: string): string {
  return entry.rename?.[recoveredValue] ?? recoveredValue.toLowerCase();
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

function code(text: string): string {
  return `\`${text}\``;
}

function enumSection(): string[] {
  const lines = [
    "### Enums",
    "",
    "| Recovered enum | Recovered values | Deyin values | Note |",
    "| --- | --- | --- | --- |",
  ];
  for (const entry of ENUMS) {
    const recovered = recoveredEnumValues(entry.recovered);
    const absent = entry.absent ?? {};
    const mapped = recovered.filter((value) => !(value in absent)).map((value) => ourValue(entry, value));
    const note = [entry.note, ...Object.entries(absent).map(([value, why]) => `${value}: ${why}`)].filter(Boolean).join(" ");
    lines.push(
      `| ${code(entry.recovered)} | ${cell(recovered.join(", "))} | ${cell(mapped.map(code).join(", "))} | ${cell(note)} |`,
    );
  }
  return lines;
}

function shapeSection(shape: ShapeParity<never>): string[] {
  const lines = [
    `#### ${code(shape.recovered)} → ${code(shape.oursName)}`,
    "",
    "| Recovered field | Deyin | Note |",
    "| --- | --- | --- |",
  ];
  for (const field of recoveredFieldNames(shape.recovered)) {
    const answer = shape.fields[field];
    if (!answer) {
      lines.push(`| ${code(field)} | **unclassified** | |`);
    } else if ("ours" in answer) {
      lines.push(`| ${code(field)} | ${code(answer.ours)} | |`);
    } else {
      lines.push(`| ${code(field)} | ${answer.gap === "not-built" ? "Not built" : "Different"} | ${cell(answer.why)} |`);
    }
  }
  if (shape.additions.length > 0) {
    lines.push("", `Deyin adds: ${shape.additions.map(code).join(", ")}.`);
  }
  return lines;
}

function surfaceSection(): string[] {
  const lines = ["### Surfaces", "", "| Surface | Status | Where | Note |", "| --- | --- | --- | --- |"];
  for (const row of SURFACES) {
    lines.push(`| ${cell(row.surface)} | ${STATUS_LABEL[row.status]} | ${cell(row.evidence.map(code).join(", "))} | ${cell(row.note)} |`);
  }
  return lines;
}

function tally(): string {
  const counts: Record<SurfaceStatus, number> = { done: 0, foundation: 0, "not-built": 0, different: 0 };
  for (const row of SURFACES) counts[row.status] += 1;
  return (Object.keys(counts) as SurfaceStatus[]).map((status) => `${counts[status]} ${STATUS_LABEL[status]}`).join(" · ");
}

export function renderParityBlock(): string {
  const lines = [
    BEGIN_MARKER,
    "",
    `**${SURFACES.length} surfaces:** ${tally()}`,
    "",
    ...surfaceSection(),
    "",
    "### Recovered contract",
    "",
    ...enumSection(),
    "",
    "### Message shapes",
    "",
  ];
  for (const shape of SHAPES) lines.push(...shapeSection(shape), "");
  lines.push(END_MARKER);
  return lines.join("\n");
}

/** Puts `block` between the markers in `doc`, or throws when the markers are not both there. */
export function withBlock(doc: string, block: string): string {
  const start = doc.indexOf(BEGIN_MARKER);
  const end = doc.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) throw new Error("PARITY-GROK-BOT.md is missing its parity markers");
  return doc.slice(0, start) + block + doc.slice(end + END_MARKER.length);
}
