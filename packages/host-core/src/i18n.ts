const DICTIONARIES: Record<Locale, Partial<Record<MessageKey, string>>> = { en, zh, de };

export function isLocale(value: string): value is Locale {
  return value === "en" || value === "zh" || value === "de";
}

/**
 * Keys a locale has no text for, so `translate` shows English instead. English itself is never missing
 * anything. Lets a test pin a feature's strings to every language, which the type system cannot
 * because the non-English dictionaries are deliberately partial.
 */
export function missingTranslations(
  locale: Locale,
  dictionaries: Record<Locale, Partial<Record<MessageKey, string>>> = DICTIONARIES,
): MessageKey[] {
  if (locale === "en") return [];
  const dict = dictionaries[locale];
  return (Object.keys(dictionaries.en) as MessageKey[]).filter((key) => !dict[key]);
}

/** Translate a key for a locale, falling back to English, then the key itself. */
export function translate(locale: string, key: MessageKey): string {
  const dict = isLocale(locale) ? DICTIONARIES[locale] : en;
  return dict[key] ?? en[key] ?? key;
}
