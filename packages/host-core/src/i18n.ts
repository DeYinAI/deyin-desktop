const DICTIONARIES: Record<Locale, Partial<Record<MessageKey, string>>> = { en, zh, de };

export function isLocale(value: string): value is Locale {
  return value === "en" || value === "zh" || value === "de";
}

/** Translate a key for a locale, falling back to English, then the key itself. */
export function translate(locale: string, key: MessageKey): string {
  const dict = isLocale(locale) ? DICTIONARIES[locale] : en;
  return dict[key] ?? en[key] ?? key;
}
